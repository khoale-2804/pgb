const (
	// pgxImport is the pgx v5 import generated scan/collect code needs.
	pgxImport = "github.com/jackc/pgx/v5"

	// Defaults mirroring ParseOptions so the passes also accept hand-built
	// Options (tests, library use).
	defaultPackage = "db"
	defaultCore    = "github.com/khoale-2804/pgb/core"
)

// normalizeOptions applies ParseOptions' defaults and fills the enum map.
func normalizeOptions(sch ir.Schema, opts Options) Options {
	if opts.Package == "" {
		opts.Package = defaultPackage
	}
	if opts.Core == "" {
		opts.Core = defaultCore
	}
	if opts.Enums == nil {
		opts.Enums = EnumTypes(sch)
	}
	return opts
}

// genHeader renders the frozen deterministic header: no timestamps.
func genHeader(opts Options) string {
	var b strings.Builder
	b.WriteString("// Code generated by pgb. DO NOT EDIT.\n")
	b.WriteString("// versions:\n")
	b.WriteString("//   pgb " + pgbVersion + "\n")
	if opts.SqlcVersion != "" {
		b.WriteString("//   sqlc " + opts.SqlcVersion + "\n")
	}
	return b.String()
}

// assembleGoFile wraps body with the header, package clause and sorted
// imports (the core runtime gets an explicit alias), then runs
// go/format.Source. Unformattable output is an error, never a warning.
func assembleGoFile(opts Options, imports []string, body string) ([]byte, error) {
	seen := map[string]bool{}
	var paths []string
	for _, p := range imports {
		if p == "" || seen[p] {
			continue
		}
		seen[p] = true
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var out strings.Builder
	out.WriteString(genHeader(opts))
	out.WriteString("\npackage " + opts.Package + "\n")
	if len(paths) > 0 {
		out.WriteString("\nimport (\n")
		for _, p := range paths {
			if p == opts.Core {
				out.WriteString("\t" + importQualifier(p) + " " + strconv.Quote(p) + "\n")
				continue
			}
			out.WriteString("\t" + strconv.Quote(p) + "\n")
		}
		out.WriteString(")\n")
	}
	out.WriteString(body)

	src, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("pgb: emitted file is not valid Go: %w", err)
	}
	return src, nil
}

// resolveColType maps one column to its Go type: the pgb:type directive
// wins, then config overrides / the builtin table via GoType. GoType's
// documented "empty means any" convention (tsvector/tsquery/pg_lsn map to
// the empty notNull type) is normalized to "any" here.
func resolveColType(t ir.Table, c ir.Column, opts Options, dir DirectiveSet) (string, []string) {
	if d := dir.Column(t.Schema, t.Name, c.Name); d.TypeOverride != "" {
		typ, imp := applyOverride(parseGoType(d.TypeOverride))
		if typ == "" {
			typ = "any"
		}
		return typ, imp
	}
	typ, imp := GoType(c, opts)
	if typ == "" {
		typ = "any"
	}
	return typ, imp
}

// genSchema reports whether a schema's tables are emitted. The catalog proto
// carries the system catalogs; stock sqlc-gen-go skips them and so do the
// pgb passes.
func genSchema(name string) bool {
	return name != "pg_catalog" && name != "information_schema"
}

// goTableNames returns the Go identifier base for one table — the plural
// descriptor name and its singular — and the generated file name stem.
// Tables outside the default schema get the schema Pascal name prefixed
// ("app.users" -> AppUsers/AppUser, file app_users.gen.go): same-name
// tables across schemas must not collide inside one package. When the
// table name is not a plural (singularize is the identity — cache_blob,
// partitions), the models pass claims the identifier for the row struct,
// so the descriptor var pluralizes instead ("CacheBlobs").
func goTableNames(sch ir.Schema, t ir.Table) (plural, singular, fileBase string) {
	p := pascalIdent(t.Name)
	fb := t.Name
	if t.Schema != "" && t.Schema != sch.DefaultSchema {
		p = pascalIdent(t.Schema) + p
		fb = t.Schema + "_" + t.Name
	}
	sg := singularize(p)
	if sg == p {
		p += "s"
	}
	return p, sg, fb
}

// fieldNames returns the exported Go field name per column (catalog order),
// deduped case-insensitively — the same rule PassModels applies, so scan
// destinations always line up with the model struct.
func fieldNames(cols []ir.Column) []string {
	seen := map[string]int{}
	names := make([]string, len(cols))
	for i, c := range cols {
		base := pascalIdent(c.Name)
		name := base
		if n := seen[strings.ToLower(base)]; n > 0 {
			name = base + strconv.Itoa(n+1)
		}
		seen[strings.ToLower(base)]++
		names[i] = name
	}
	return names
}

// qualifiedTable renders the schema-qualified table reference used in
// emitted FROM/INTO/UPDATE targets ("public.users").
func qualifiedTable(t ir.Table) string {
	if t.Schema == "" {
		return t.Name
	}
	return t.Schema + "." + t.Name
}

// textTypes / orderedTypes classify columns into the predicate families of
// docs/generated-code/builders (keys mirror maptype.go's builtin table).
var textTypes = map[string]bool{
	"text": true, "varchar": true, "bpchar": true, "citext": true,
	"name": true, "xml": true,
}

var orderedTypes = map[string]bool{
	"int2": true, "smallint": true, "int4": true, "integer": true, "int": true,
	"serial": true, "int8": true, "bigint": true, "bigserial": true, "smallserial": true,
	"float4": true, "real": true, "float8": true, "double precision": true,
	"numeric": true, "decimal": true, "money": true,
	"timestamptz": true, "timestamp": true, "date": true, "time": true, "timetz": true,
}

// inTypes are the remaining base types whose array form pgx encodes for
// "col = ANY($1::base[])" — everything exotic (geo, ranges, tid, xid8)
// keeps Eq/Ne but loses In.
var inTypes = map[string]bool{
	"bool": true, "boolean": true, "uuid": true, "bytea": true,
	"inet": true, "cidr": true, "macaddr": true, "macaddr8": true,
}

// colCaps lists which predicate families a column supports.
type colCaps struct {
	eq       bool // Eq/Ne (bound Lit)
	in       bool // In (...T) via "col = ANY($1::base[])"
	ordered  bool // Gt/Lt/Gte/Lte/Between
	text     bool // Like/ILike/NotLike/NotILike
	json     bool // KeyEq (Raw with renumbered args)
	contains bool // Contains ("col @> $1::base[]")
}

// capsFor derives the predicate capability set: Eq/Ne (plus the argument-free
// IsNull/NotNull) on all columns; In on encodable non-array non-json types;
// ordered/text/json/array families per maptype's classification. Scalar enums
// keep Eq/Ne only (In would need an enum[] codec); enum-typed arrays and
// columns typed "any" keep only the null checks.
func capsFor(c ir.Column, goType string, opts Options) colCaps {
	base := strings.ToLower(c.PGType)
	isEnum := opts.Enums[base] != ""
	var caps colCaps
	if !c.IsArray {
		caps.eq = true
		switch {
		case base == "json" || base == "jsonb":
			caps.json = true
		case isEnum:
			// scalar enum: Eq/Ne only
		case textTypes[base]:
			caps.text = true
			caps.in = goType != "any"
		case orderedTypes[base]:
			caps.ordered = true
			caps.in = goType != "any"
		default:
			caps.in = goType != "any" && inTypes[base]
		}
		return caps
	}
	if isEnum {
		return caps // enum arrays: null checks only
	}
	caps.eq = goType != "any"
	caps.contains = goType != "any"
	return caps
}

// litCast is the ::cast hint for value parameters: json/jsonb pins the
// document type (pgx sends []byte as bytea), enums pin their type name,
// arrays pin "<base>[]". Empty means pgx's server-inferred OID is already
// right (every value stays a bound parameter either way).
func litCast(c ir.Column, opts Options) string {
	base := strings.ToLower(c.PGType)
	if c.IsArray {
		if opts.Enums[base] != "" {
			return "" // enum arrays carry no value predicates
		}
		return base + "[]"
	}
	switch base {
	case "json", "jsonb":
		return base
	}
	if opts.Enums[base] != "" {
		return base
	}
	return ""
}

// inCast is the array cast for "= ANY" parameters. Text-family columns use
// text[] (varchar/citext compare against text natively); everything else
// uses its own base type.
func inCast(c ir.Column, opts Options) string {
	base := strings.ToLower(c.PGType)
	if textTypes[base] {
		return "text[]"
	}
	return base + "[]"
}

// litExpr renders a core.Lit expression for value v with the column's cast
// hint applied — shared by the builder and statics emitters.
func litExpr(c ir.Column, v string, opts Options) string {
	if cast := litCast(c, opts); cast != "" {
		return "core.Lit{V: " + v + ", Cast: " + strconv.Quote(cast) + "}"
	}
	return "core.Lit{V: " + v + "}"
}

// PassBuilders emits pass B: one "<table>.gen.go" per non-skip table with
// the table descriptor (embedded core.TableMeta), typed column accessors,
// predicate methods by type family, and the Select/Update/Delete entry
// points. Ordering is catalog order and the file list is sorted; every
// value stays a bound parameter. In renders as "col = ANY($1::base[])",
// Between as "(col >= $1 AND col <= $2)" via core.And, KeyEq as a Raw with
// renumbered args, Contains as "col @> $1::base[]".
func PassBuilders(sch ir.Schema, opts Options, dir DirectiveSet) ([]plugin.File, error) {
	opts = normalizeOptions(sch, opts)
	var files []plugin.File
	for _, t := range sch.Tables {
		if t.Skip || dir.Table(t.Schema, t.Name).Skip || !genSchema(t.Schema) {
			continue
		}
		src, err := buildersFile(sch, t, opts, dir)
		if err != nil {
			return nil, fmt.Errorf("pgb: builders for %s: %w", t.Name, err)
		}
		_, _, fb := goTableNames(sch, t)
		files = append(files, plugin.File{Name: fb + ".gen.go", Contents: src})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Name < files[j].Name })
	return files, nil
}

// reservedMethods are the table-level entry points every descriptor carries;
// a column whose Pascal name matches one gets a suffixed accessor method
// ("select" column -> SelectCol) so the two never collide.
var reservedMethods = map[string]bool{"Select": true, "Update": true, "Delete": true}

// accessorName is the descriptor method name for a column accessor.
func accessorName(field string) string {
	if reservedMethods[field] {
		return field + "Col"
	}
	return field
}

// colLiteral renders a raw core.Col expression for one column — used in
// SELECT column lists and RETURNING clauses so they never depend on
// accessor methods.
func colLiteral(t ir.Table, c ir.Column) string {
	return "core.Col{Table: " + strconv.Quote(t.Name) + ", Name: " + strconv.Quote(c.Name) + "}"
}

// buildersFile emits the descriptor file for one table.
func buildersFile(sch ir.Schema, t ir.Table, opts Options, dir DirectiveSet) ([]byte, error) {
	tableVar, _, _ := goTableNames(sch, t)
	tableType := singularize(tableVar) + "Table"
	base := strings.TrimSuffix(tableType, "Table")
	qname := qualifiedTable(t)
	names := fieldNames(t.Columns)

	imports := []string{opts.Core}

	var b strings.Builder
	fmt.Fprintf(&b, "// %s is the table descriptor for %s; immutable, safe for\n// concurrent use.\n", tableVar, qname)
	fmt.Fprintf(&b, "var %s = %s{core.NewTableMeta(%s, %s)}\n\n",
		tableVar, tableType, strconv.Quote(t.Schema), strconv.Quote(t.Name))
	fmt.Fprintf(&b, "// %s provides typed column accessors and statement entry points.\n", tableType)
	fmt.Fprintf(&b, "type %s struct{ core.TableMeta }\n\n", tableType)

	for i, c := range t.Columns {
		field := names[i]
		colType := base + field + "Col"
		typ, imp := resolveColType(t, c, opts, dir)
		noFilter := dir.Column(t.Schema, t.Name, c.Name).NoFilter
		if !noFilter {
			imports = append(imports, imp...)
		}

		fmt.Fprintf(&b, "// %s returns the typed accessor for column %s.\n", accessorName(field), c.Name)
		fmt.Fprintf(&b, "func (t %s) %s() %s {\n\treturn %s{core.Col{Table: %s, Name: %s}}\n}\n\n",
			tableType, accessorName(field), colType, colType, strconv.Quote(t.Name), strconv.Quote(c.Name))
		fmt.Fprintf(&b, "// %s is the typed column %s.%s.\n", colType, t.Name, c.Name)
		fmt.Fprintf(&b, "type %s struct{ core.Col }\n\n", colType)

		if !noFilter {
			emitPredicates(&b, colType, c, typ, capsFor(c, typ, opts), opts)
		}
	}

	cols := make([]string, len(t.Columns))
	for i := range t.Columns {
		cols[i] = colLiteral(t, t.Columns[i])
	}
	b.WriteString("// Select starts a SELECT of every column; chain Where/OrderBy/Limit/...\n// and terminate with Run (or a static function).\n")
	fmt.Fprintf(&b, "func (t %s) Select() *core.Select {\n\treturn core.NewSelect(%s, %s)\n}\n\n",
		tableType, strconv.Quote(qname), strings.Join(cols, ", "))
	if !t.View {
		b.WriteString("// Update starts an UPDATE; an empty WHERE fails with core.ErrNoWhere.\n")
		fmt.Fprintf(&b, "func (t %s) Update() *core.Update { return core.NewUpdate(%s) }\n\n", tableType, strconv.Quote(qname))
		b.WriteString("// Delete starts a DELETE; an empty WHERE fails with core.ErrNoWhere.\n")
		fmt.Fprintf(&b, "func (t %s) Delete() *core.Delete { return core.NewDelete(%s) }\n", tableType, strconv.Quote(qname))
	}
	return assembleGoFile(opts, imports, b.String())
}

// emitPredicates writes the predicate methods for one typed column, gated by
// its capability set. Shapes follow docs/generated-code/builders: Eq/Ne bind
// a Lit, In is "col = ANY($1::base[])", ordered comparisons are plain Bin,
// Between wraps two comparisons in core.And, text predicates bind the
// pattern, KeyEq is a Raw ("col ->> $n = $m") whose args renumber, and
// Contains is "col @> $1::base[]".
func emitPredicates(b *strings.Builder, colType string, c ir.Column, goType string, caps colCaps, opts Options) {
	lit := func(v string) string { return litExpr(c, v, opts) }
	bin := func(name, op, param, val string) {
		fmt.Fprintf(b, "func (c %[1]s) %[2]s(%[3]s) core.Expr {\n\treturn core.Bin{Op: %[4]s, L: c.Col, R: %[5]s}\n}\n\n",
			colType, name, param, strconv.Quote(op), val)
	}

	if caps.eq {
		bin("Eq", "=", "v "+goType, lit("v"))
		bin("Ne", "!=", "v "+goType, lit("v"))
	}
	if caps.in {
		bin("In", "= ANY", "vs ..."+goType,
			"core.Lit{V: vs, Cast: "+strconv.Quote(inCast(c, opts))+"}")
	}
	// IsNull/NotNull exist on every column, value or not.
	fmt.Fprintf(b, "func (c %[1]s) IsNull() core.Expr {\n\treturn core.Raw{SQL: core.QuoteIdent(c.Col.Table, c.Col.Name) + \" IS NULL\"}\n}\n\n", colType)
	fmt.Fprintf(b, "func (c %[1]s) NotNull() core.Expr {\n\treturn core.Raw{SQL: core.QuoteIdent(c.Col.Table, c.Col.Name) + \" IS NOT NULL\"}\n}\n\n", colType)

	if caps.ordered {
		bin("Gt", ">", "v "+goType, lit("v"))
		bin("Lt", "<", "v "+goType, lit("v"))
		bin("Gte", ">=", "v "+goType, lit("v"))
		bin("Lte", "<=", "v "+goType, lit("v"))
		fmt.Fprintf(b, "func (c %[1]s) Between(a, b %[2]s) core.Expr {\n\treturn core.And{Parts: []core.Expr{\n\t\tcore.Bin{Op: \">=\", L: c.Col, R: %[3]s},\n\t\tcore.Bin{Op: \"<=\", L: c.Col, R: %[4]s},\n\t}}\n}\n\n",
			colType, goType, lit("a"), lit("b"))
	}
	if caps.text {
		bin("Like", "LIKE", "p string", "core.Lit{V: p}")
		bin("ILike", "ILIKE", "p string", "core.Lit{V: p}")
		bin("NotLike", "NOT LIKE", "p string", "core.Lit{V: p}")
		bin("NotILike", "NOT ILIKE", "p string", "core.Lit{V: p}")
	}
	if caps.json {
		fmt.Fprintf(b, "func (c %[1]s) KeyEq(path string, v any) core.Expr {\n\treturn core.Raw{SQL: core.QuoteIdent(c.Col.Table, c.Col.Name) + \" ->> ?\", Args: []any{path, v}}\n}\n\n", colType)
	}
	if caps.contains {
		bin("Contains", "@>", "v "+goType, lit("v"))
	}
}
