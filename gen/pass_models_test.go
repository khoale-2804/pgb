// fakeRequest mirrors the CONTRACTS test schema: users with mixed types, an
// enum, a nullable jsonb and the keyword column "range"; products with a
// vector column resolved by a config override; audit_log behind pgb:skip.
func fakeRequest() *plugin.GenerateRequest {
	return &plugin.GenerateRequest{
		SqlcVersion: "v1.31.1",
		PluginOptions: []byte(`{"package":"db","overrides":[` +
			`{"db_type":"vector","go_type":"github.com/pgvector/pgvector-go.Vector"}]}`),
		Catalog: &plugin.Catalog{
			DefaultSchema: "public",
			Schemas: []*plugin.Schema{{
				Name: "public",
				Enums: []*plugin.Enum{
					{Name: "user_status", Vals: []string{"active", "inactive"}},
				},
				Tables: []*plugin.Table{
					{
						Rel: &plugin.Identifier{Schema: "public", Name: "users"},
						Columns: []*plugin.Column{
							{Name: "id", NotNull: true, Type: &plugin.Identifier{Name: "int8"}},
							{Name: "email", NotNull: true, Type: &plugin.Identifier{Name: "text"}},
							{Name: "bio", Type: &plugin.Identifier{Name: "text"}, Comment: "free-form text; pgb:no_filter"},
							{Name: "status", NotNull: true, Type: &plugin.Identifier{Name: "public.user_status"}},
							{Name: "metadata", Type: &plugin.Identifier{Name: "jsonb"}},
							{Name: "tags", IsArray: true, Type: &plugin.Identifier{Name: "text"}},
							{Name: "account_id", Type: &plugin.Identifier{Name: "uuid"}},
							{Name: "created_at", NotNull: true, Type: &plugin.Identifier{Name: "timestamptz"}},
							{Name: "range", NotNull: true, Type: &plugin.Identifier{Name: "int4"}},
						},
					},
					{
						Rel: &plugin.Identifier{Schema: "public", Name: "products"},
						Columns: []*plugin.Column{
							{Name: "id", NotNull: true, Type: &plugin.Identifier{Name: "int8"}},
							{Name: "embedding", NotNull: true, Type: &plugin.Identifier{Name: "vector"}},
						},
					},
					{
						Rel:     &plugin.Identifier{Schema: "public", Name: "audit_log"},
						Comment: "internal trail; pgb:skip",
						Columns: []*plugin.Column{
							{Name: "payload", Type: &plugin.Identifier{Name: "jsonb"}},
						},
					},
				},
			}},
		},
	}
}

// fieldLine finds the generated struct-field line whose first token is field.
func fieldLine(t *testing.T, out, field string) []string {
	t.Helper()
	for _, line := range strings.Split(out, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, field+" ") {
			return strings.Fields(trimmed)
		}
	}
	t.Fatalf("field %q not found in output:\n%s", field, out)
	return nil
}

func wantField(t *testing.T, out, field, typ, tag string) {
	t.Helper()
	parts := fieldLine(t, out, field)
	if len(parts) < 3 {
		t.Fatalf("field %q line too short: %v", field, parts)
	}
	if parts[1] != typ {
		t.Errorf("field %s: got type %s, want %s", field, parts[1], typ)
	}
	if parts[len(parts)-1] != "`json:\""+tag+"\"`" {
		t.Errorf("field %s: got tag %s, want json tag %q", field, parts[len(parts)-1], tag)
	}
}

func TestBuild(t *testing.T) {
	req := fakeRequest()
	sch, dir, err := Build(req, ParseOptions(req))
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	if sch.DefaultSchema != "public" {
		t.Errorf("DefaultSchema = %q", sch.DefaultSchema)
	}
	if len(sch.Tables) != 3 {
		t.Fatalf("tables = %d, want 3", len(sch.Tables))
	}
	if len(sch.Enums) != 1 || sch.Enums[0].Name != "user_status" {
		t.Fatalf("enums = %+v", sch.Enums)
	}
	users := sch.Tables[0]
	if users.Name != "users" || len(users.Columns) != 9 {
		t.Fatalf("users table = %+v", users)
	}
	bio := users.Columns[2]
	if bio.PGType != "text" || bio.Comment != "free-form text" {
		t.Errorf("bio column = %+v", bio)
	}
	status := users.Columns[3]
	if status.PGType != "user_status" {
		t.Errorf("status PGType = %q, want user_status (schema qualifier stripped)", status.PGType)
	}
	if !dir.Column("public", "users", "bio").NoFilter {
		t.Error("bio should carry pgb:no_filter")
	}
	if dir.Table("public", "audit_log").Skip != true {
		t.Error("audit_log should carry pgb:skip")
	}
	if dir.Table("public", "users").Has() {
		t.Error("users should have no table directives")
	}
	if !Nullable(bio) || Nullable(users.Columns[0]) {
		t.Error("Nullable() disagrees with NotNull")
	}
}

func TestPassModels(t *testing.T) {
	req := fakeRequest()
	opts := ParseOptions(req)
	sch, dir, err := Build(req, opts)
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	out, err := PassModels(sch, opts, dir)
	if err != nil {
		t.Fatalf("PassModels: %v", err)
	}
	s := string(out)

	// Header + package.
	for _, want := range []string{
		"// Code generated by pgb. DO NOT EDIT.",
		"// versions:",
		"//   pgb " + pgbVersion,
		"//   sqlc v1.31.1",
		"package db",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("output missing %q", want)
		}
	}

	// User struct: mixed types.
	wantField(t, s, "ID", "int64", "id")
	wantField(t, s, "Email", "string", "email")
	wantField(t, s, "Bio", "pgtype.Text", "bio")
	wantField(t, s, "Status", "UserStatus", "status")
	wantField(t, s, "Metadata", "[]byte", "metadata")
	wantField(t, s, "Tags", "[]string", "tags")
	wantField(t, s, "AccountID", "uuid.NullUUID", "account_id")
	wantField(t, s, "CreatedAt", "pgtype.Timestamptz", "created_at")
	wantField(t, s, "Range", "int32", "range") // keyword column, exported field

	// Enums.
	if !strings.Contains(s, "type UserStatus string") {
		t.Error("missing enum type UserStatus")
	}
	if !strings.Contains(s, "UserStatusActive") || !strings.Contains(s, `"active"`) {
		t.Error("missing enum const UserStatusActive")
	}
	if !strings.Contains(s, "UserStatusInactive") || !strings.Contains(s, `"inactive"`) {
		t.Error("missing enum const UserStatusInactive")
	}

	// Product struct with the vector override.
	wantField(t, s, "Embedding", "pgvector.Vector", "embedding")

	// Imports present and sorted.
	pgtype := strings.Index(s, `"github.com/jackc/pgx/v5/pgtype"`)
	uuid := strings.Index(s, `"github.com/google/uuid"`)
	pgvector := strings.Index(s, `"github.com/pgvector/pgvector-go"`)
	if pgtype < 0 || uuid < 0 || pgvector < 0 {
		t.Fatalf("missing imports (pgtype=%d uuid=%d pgvector=%d)", pgtype, uuid, pgvector)
	}
	if !(uuid < pgtype && pgtype < pgvector) {
		t.Errorf("imports not sorted (uuid=%d pgtype=%d pgvector=%d)", uuid, pgtype, pgvector)
	}

	// pgb:skip table emits nothing.
	if strings.Contains(s, "AuditLog") {
		t.Error("pgb:skip table leaked into models")
	}
}

func TestGoType(t *testing.T) {
	tests := []struct {
		name    string
		col     ir.Column
		opts    Options
		want    string
		imports int
	}{
		{"int4 not null", ir.Column{PGType: "int4", NotNull: true}, Options{}, "int32", 0},
		{"int4 nullable", ir.Column{PGType: "int4"}, Options{}, "pgtype.Int4", 1},
		{"text nullable", ir.Column{PGType: "text"}, Options{}, "pgtype.Text", 1},
		{"timestamptz not null keeps wrapper", ir.Column{PGType: "timestamptz", NotNull: true}, Options{}, "pgtype.Timestamptz", 1},
		{"jsonb", ir.Column{PGType: "jsonb"}, Options{}, "[]byte", 0},
		{"text array", ir.Column{PGType: "text", IsArray: true}, Options{}, "[]string", 0},
		{"range", ir.Column{PGType: "int4range", NotNull: true}, Options{}, "pgtype.Range[pgtype.Int4]", 1},
		{"multirange", ir.Column{PGType: "datemultirange", NotNull: true}, Options{}, "pgtype.Multirange[pgtype.Range[pgtype.Date]]", 1},
		{"inet deviation", ir.Column{PGType: "inet", NotNull: true}, Options{}, "netip.Prefix", 1},
		{"macaddr deviation", ir.Column{PGType: "macaddr", NotNull: true}, Options{}, "net.HardwareAddr", 1},
		{"timetz deviation", ir.Column{PGType: "timetz", NotNull: true}, Options{}, "pgtype.Time", 1},
		{"geometric", ir.Column{PGType: "point", NotNull: true}, Options{}, "pgtype.Point", 1},
		{"geo array -> any", ir.Column{PGType: "point", IsArray: true}, Options{}, "any", 0},
		{"unknown", ir.Column{PGType: "weirdo", NotNull: true}, Options{}, "any", 0},
		{"enum", ir.Column{PGType: "user_status", NotNull: true}, Options{Enums: map[string]string{"user_status": "UserStatus"}}, "UserStatus", 0},
	}
	for _, tt := range tests {
		got, imports := GoType(tt.col, tt.opts)
		if got != tt.want {
			t.Errorf("%s: GoType = %q, want %q", tt.name, got, tt.want)
		}
		if len(imports) != tt.imports {
			t.Errorf("%s: imports = %v, want %d entries", tt.name, imports, tt.imports)
		}
	}

	// DBType override via the parsed config form.
	o := ParseOptions(fakeRequest())
	got, imports := GoType(ir.Column{PGType: "vector", NotNull: true}, o)
	if got != "pgvector.Vector" || len(imports) != 1 || imports[0] != "github.com/pgvector/pgvector-go" {
		t.Errorf("vector override: got %q %v", got, imports)
	}

	// Column override wins over DBType.
	o.Overrides = append(o.Overrides, TypeOverride{Column: "products.embedding", Type: "map[string]any"})
	got, _ = GoType(ir.Column{Name: "embedding", PGType: "vector", NotNull: true}, o)
	if got != "map[string]any" {
		t.Errorf("column override: got %q, want map[string]any", got)
	}

	// Nullable is !NotNull regardless of overrides.
	if Nullable(ir.Column{PGType: "text"}) != true || Nullable(ir.Column{PGType: "text", NotNull: true}) != false {
		t.Error("Nullable broken")
	}
}

