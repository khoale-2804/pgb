func TestHeuristicPK(t *testing.T) {
	yes := ir.Table{Columns: []ir.Column{{Name: "id", PGType: "int8", NotNull: true}}}
	if got := heuristicPK(yes); got == nil {
		t.Error("single NOT NULL id should be the heuristic PK")
	}
	nullable := ir.Table{Columns: []ir.Column{{Name: "id", PGType: "int8"}}}
	if got := heuristicPK(nullable); got != nil {
		t.Error("nullable id is not a key")
	}
	composite := ir.Table{PrimaryKey: []string{"tenant_id", "id"}, Columns: []ir.Column{
		{Name: "id", PGType: "int8", NotNull: true},
	}}
	if got := heuristicPK(composite); got != nil {
		t.Error("explicit composite key must disable the heuristic")
	}
}

func TestPassesSkipTablesAndSchemas(t *testing.T) {
	b, err := PassBuilders(staticsSchema(), Options{}, staticsDirectives())
	if err != nil {
		t.Fatalf("PassBuilders: %v", err)
	}
	s, err := PassStatics(staticsSchema(), Options{}, staticsDirectives())
	if err != nil {
		t.Fatalf("PassStatics: %v", err)
	}
	for _, files := range [][]plugin.File{b, s} {
		for i := range files {
			c := files[i].Contents
			if strings.Contains(string(c), "AuditLog") || strings.Contains(files[i].Name, "audit_log") {
				t.Errorf("pgb:skip table leaked into %s", files[i].Name)
			}
			if strings.Contains(string(c), "PgClass") || strings.Contains(files[i].Name, "pg_class") {
				t.Errorf("pg_catalog table leaked into %s", files[i].Name)
			}
		}
	}
}
