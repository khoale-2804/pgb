// staticsSchema is the fake table set for the builders/statics pass tests:
// users with a heuristic id PK, mixed type families, a default-bearing
// column, a nullable jsonb, a text array — plus a PK-less orders table, an
// app-schema users twin (package-safe naming), a pg_catalog table (system
// schemas are skipped) and a pgb:skip audit_log.
func staticsSchema() ir.Schema {
	return ir.Schema{
		DefaultSchema: "public",
		Tables: []ir.Table{
			{
				Schema: "public",
				Name:   "users",
				Columns: []ir.Column{
					{Name: "id", PGType: "int8", NotNull: true},
					{Name: "email", PGType: "text", NotNull: true},
					{Name: "password", PGType: "text", NotNull: true},
					{Name: "bio", PGType: "text"},
					{Name: "metadata", PGType: "jsonb"},
					{Name: "tags", PGType: "text", IsArray: true},
					{Name: "created_at", PGType: "timestamptz", NotNull: true, HasDefault: true},
					{Name: "last_login_at", PGType: "timestamptz"},
					{Name: "tsv", PGType: "tsvector", NotNull: true}, // empty GoType -> any
				},
			},
			{
				Schema: "public",
				Name:   "orders",
				Columns: []ir.Column{
					{Name: "tenant_id", PGType: "int8", NotNull: true},
					{Name: "total", PGType: "numeric", NotNull: true},
				},
			},
			{
				Schema: "app",
				Name:   "users",
				Columns: []ir.Column{
					{Name: "id", PGType: "int8", NotNull: true},
					{Name: "login", PGType: "text", NotNull: true},
					{Name: "select", PGType: "text"}, // reserved method name
				},
			},
			{
				Schema: "pg_catalog",
				Name:   "pg_class",
				Columns: []ir.Column{
					{Name: "oid", PGType: "oid", NotNull: true},
				},
			},
			{
				Schema: "public",
				Name:   "audit_log",
				Skip:   true,
				Columns: []ir.Column{
					{Name: "payload", PGType: "jsonb"},
				},
			},
		},
	}
}

// staticsDirectives hides users.password from filters and patches.
func staticsDirectives() DirectiveSet {
	return DirectiveSet{Columns: map[string]Directives{
		"public.users.password": {NoFilter: true, NoPatch: true},
	}}
}

// norm collapses runs of whitespace so assertions survive gofmt's struct
// field alignment.
func norm(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// wantSubs asserts every substring is present (whitespace-insensitive).
func wantSubs(t *testing.T, s string, subs ...string) {
	t.Helper()
	n := norm(s)
	for _, sub := range subs {
		if !strings.Contains(n, norm(sub)) {
			t.Errorf("output missing %q", sub)
		}
	}
}

// noneSubs asserts no substring is present (whitespace-insensitive).
func noneSubs(t *testing.T, s string, subs ...string) {
	t.Helper()
	n := norm(s)
	for _, sub := range subs {
		if strings.Contains(n, norm(sub)) {
			t.Errorf("output must not contain %q", sub)
		}
	}
}

// block returns the source from start through the first "\n}" (a top-level
// struct block).
func block(s, start string) string {
	i := strings.Index(s, start)
	if i < 0 {
		return ""
	}
	j := strings.Index(s[i:], "\n}")
	if j < 0 {
		return s[i:]
	}
	return s[i : i+j+2]
}

// funcBlock returns the source from sig through the next top-level func.
func funcBlock(s, sig string) string {
	i := strings.Index(s, sig)
	if i < 0 {
		return ""
	}
	j := strings.Index(s[i+1:], "\nfunc ")
	if j < 0 {
		return s[i:]
	}
	return s[i : i+1+j]
}

// fileByName fetches one emitted file's contents by name.
func fileByName(t *testing.T, files []plugin.File, name string) string {
	t.Helper()
	for i := range files {
		if files[i].Name == name {
			return string(files[i].Contents)
		}
	}
	var have []string
	for i := range files {
		have = append(have, files[i].Name)
	}
	t.Fatalf("file %q not found; have %v", name, have)
	return ""
}

func fileNames(files []plugin.File) []string {
	var out []string
	for i := range files {
		out = append(out, files[i].Name)
	}
	return out
}

func TestPassBuilders(t *testing.T) {
	files, err := PassBuilders(staticsSchema(), Options{}, staticsDirectives())
	if err != nil {
		t.Fatalf("PassBuilders: %v", err)
	}
	if len(files) != 3 {
		t.Fatalf("files = %v, want app_users + orders + users .gen.go", fileNames(files))
	}

	u := fileByName(t, files, "users.gen.go")
	wantSubs(t, u,
		"// Code generated by pgb. DO NOT EDIT.",
		"// versions:",
		"package db",
		`pgb "github.com/khoale-2804/pgb/core"`,
		`var Users = UserTable{pgb.NewTableMeta("public", "users")}`,
		"type UserTable struct{ pgb.TableMeta }",
		"func (t UserTable) ID() UserIDCol {",
		`pgb.Col{Table: "users", Name: "id"}`,
		"type UserEmailCol struct{ pgb.Col }",
		"func (c UserIDCol) Eq(v int64) pgb.Expr {",
		`Op: "=", L: c.Col, R: pgb.Lit{V: v}`,
		"func (c UserEmailCol) In(vs ...string) pgb.Expr {",
		`" = ANY(?::" + "text[]" + ")"`,
		`Args: []any{vs}`,
		"func (c UserTsvCol) Eq(v any) pgb.Expr {", // empty GoType normalized to any
		"func (c UserBioCol) IsNull() pgb.Expr {",
		`" IS NULL"`,
		`" IS NOT NULL"`,
		"func (c UserCreatedAtCol) Gt(v pgtype.Timestamptz) pgb.Expr {",
		"func (c UserCreatedAtCol) Between(a, b pgtype.Timestamptz) pgb.Expr {",
		`pgb.Bin{Op: ">=", L: c.Col, R: pgb.Lit{V: a}}`,
		`pgb.Bin{Op: "<=", L: c.Col, R: pgb.Lit{V: b}}`,
		"func (c UserEmailCol) Like(p string) pgb.Expr {",
		`Op: "LIKE"`,
		"func (c UserMetadataCol) KeyEq(path string, v any) pgb.Expr {",
		`pgb.QuoteIdent(c.Col.Table, c.Col.Name) + " ->> ? = ?"`,
		"func (c UserTagsCol) Contains(v []string) pgb.Expr {",
		`Op: "@>"`,
		`Cast: "text[]"`,
		`pgb.NewSelect("public.users"`,
		"func (t UserTable) Select() *pgb.Select {",
		`func (t UserTable) Update() *pgb.Update { return pgb.NewUpdate("public.users") }`,
		`func (t UserTable) Delete() *pgb.Delete { return pgb.NewDelete("public.users") }`,
	)
	// pgb:no_filter column keeps its accessor but loses every predicate.
	if !strings.Contains(u, "func (t UserTable) Password() UserPasswordCol {") {
		t.Error("missing accessor for pgb:no_filter column")
	}
	noneSubs(t, u,
		"func (c UserPasswordCol) Eq(",
		"func (c UserPasswordCol) In(",
		"func (c UserPasswordCol) IsNull(",
	)

	// Second schema, same table name: package-safe prefixed naming.
	a := fileByName(t, files, "app_users.gen.go")
	wantSubs(t, a,
		`var AppUsers = AppUserTable{pgb.NewTableMeta("app", "users")}`,
		"type AppUserTable struct{ pgb.TableMeta }",
		`pgb.NewSelect("app.users"`,
		// a column named "select" must not collide with the table-level
		// Select(): its accessor is renamed, the SELECT list uses raw Cols
		"func (t AppUserTable) SelectCol() AppUserSelectCol {",
		`func (t AppUserTable) Select() *pgb.Select {`,
		`pgb.Col{Table: "users", Name: "select"}`,
	)

	_ = fileByName(t, files, "orders.gen.go") // PK-less table still gets a descriptor
}

func TestPassStatics(t *testing.T) {
	files, err := PassStatics(staticsSchema(), Options{}, staticsDirectives())
	if err != nil {
		t.Fatalf("PassStatics: %v", err)
	}
	if len(files) != 4 {
		t.Fatalf("files = %v, want app/users repos + orders_repo + pgb_helpers", fileNames(files))
	}

	u := fileByName(t, files, "users_repo.gen.go")

	// Static signatures (docs/generated-code/statics shapes, frozen-slice
	// simplifications: limit int, id-based upsert).
	wantSubs(t, u,
		"// Code generated by pgb. DO NOT EDIT.",
		"package db",
		"func GetUser(ctx context.Context, exec pgb.DBTX, id int64) (User, error) {",
		"func ListUsers(ctx context.Context, exec pgb.DBTX, f UserFilter, opts ...pgb.ListOpt) ([]User, error) {",
		"func CountUsers(ctx context.Context, exec pgb.DBTX, f UserFilter) (int64, error) {",
		"func InsertUser(ctx context.Context, exec pgb.DBTX, p InsertUserParams) (User, error) {",
		"func UpdateUser(ctx context.Context, exec pgb.DBTX, id int64, s UserSet) (User, error) {",
		"func UpdateUsers(ctx context.Context, exec pgb.DBTX, where []pgb.Expr, s UserSet) (int64, error) {",
		"func UpsertUser(ctx context.Context, exec pgb.DBTX, id int64, p InsertUserParams) (User, error) {",
		"func DeleteUser(ctx context.Context, exec pgb.DBTX, id int64) error {",
		"func DeleteUsers(ctx context.Context, exec pgb.DBTX, where []pgb.Expr) (int64, error) {",
		"func scanUser(row pgx.CollectableRow) (User, error) {",
		"pgx.CollectRows(rows, scanUser)",
		"usersFilterWhere(f)...",
		`pgb.NewSelect("public.users", pgb.Raw{SQL: "count(*)"})`,
	)

	// GetUser: ErrNotFound via pgx.ErrNoRows mapping, and no ErrNoWhere
	// anywhere inside it.
	getUser := funcBlock(u, "func GetUser(")
	if getUser == "" {
		t.Fatal("GetUser not emitted")
	}
	wantSubs(t, getUser, "pgb.ErrNotFound", "errors.Is(err, pgx.ErrNoRows)")
	noneSubs(t, getUser, "ErrNoWhere")

	// tsv resolves to "any" (maptype's empty notNull convention), which pgx
	// cannot encode as an unnest array parameter — InsertUsers is skipped.
	noneSubs(t, u, "func InsertUsers(")

	// Upsert: ON CONFLICT (id) DO UPDATE SET ... = EXCLUDED....
	upsert := funcBlock(u, "func UpsertUser(")
	if upsert == "" {
		t.Fatal("UpsertUser not emitted")
	}
	wantSubs(t, upsert,
		`Target: []string{"id"}`,
		`{Col: "email", E: pgb.Col{Table: "excluded", Name: "email"}}`,
		"pgb.ErrNotFound",
	)

	// ErrNoWhere guards live on the bulk mutations only.
	wantSubs(t, u, "pgb.ErrNoWhere")
	noneSubs(t, funcBlock(u, "func InsertUser("), "ErrNoWhere")

	// UserSet: three-state fields, no pgb:no_patch column, no PK column.
	setBlock := block(u, "type UserSet struct {")
	if setBlock == "" {
		t.Fatal("UserSet not emitted")
	}
	wantSubs(t, setBlock,
		"Email Set[string]", "Bio Set[pgtype.Text]", "Metadata Set[[]byte]",
		"Tags Set[[]string]", "LastLoginAt Set[pgtype.Timestamptz]", "Tsv Set[any]")
	noneSubs(t, setBlock, "Password", "ID Set[")

	// UserFilter: typed optional fields per family, pgb:no_filter excluded.
	f := block(u, "type UserFilter struct {")
	wantSubs(t, f,
		"ID *int64", "IDIn []int64", "Email *string", "EmailIn []string",
		"EmailLike *string", "EmailILike *string", "Bio *pgtype.Text",
		"BioIn []pgtype.Text", "Metadata *[]byte", "Tags *[]string",
		"CreatedAtGt *pgtype.Timestamptz", "CreatedAtGte *pgtype.Timestamptz",
		"Tsv *any", "Extra []pgb.Expr")
	noneSubs(t, f, "Password")

	// InsertUserParams: default-bearing column stays out.
	p := block(u, "type InsertUserParams struct {")
	wantSubs(t, p,
		"ID int64", "Email string", "Password string", "Bio pgtype.Text",
		"Metadata []byte", "Tags []string", "LastLoginAt pgtype.Timestamptz", "Tsv any")
	noneSubs(t, p, "CreatedAt")

	// No keyset page functions in this slice.
	noneSubs(t, u, "Page(")

	// PK-less table: bulk + insert statics only, no single-row-by-id functions.
	o := fileByName(t, files, "orders_repo.gen.go")
	wantSubs(t, o,
		"func ListOrders(ctx context.Context, exec pgb.DBTX, f OrderFilter, opts ...pgb.ListOpt) ([]Order, error) {",
		"func CountOrders(ctx context.Context, exec pgb.DBTX, f OrderFilter) (int64, error) {",
		"func InsertOrder(ctx context.Context, exec pgb.DBTX, p InsertOrderParams) (Order, error) {",
		"func InsertOrders(ctx context.Context, exec pgb.DBTX, ps []InsertOrderParams) ([]Order, error) {",
		// unnest batch shape: one array parameter per insertable column,
		// cast to its base type; RETURNING covers every catalog column.
		`SELECT * FROM unnest($1::int8[], $2::numeric[]`,
		`RETURNING tenant_id, total"`,
		"insertOrdersSQL",
		"func UpdateOrders(ctx context.Context, exec pgb.DBTX, where []pgb.Expr, s OrderSet) (int64, error) {",
		"func DeleteOrders(ctx context.Context, exec pgb.DBTX, where []pgb.Expr) (int64, error) {",
	)
	noneSubs(t, o,
		"func GetOrder(", "func UpdateOrder(", "func UpsertOrder(", "func DeleteOrder(",
	)

	// Second schema: prefixed statics for app.users.
	a := fileByName(t, files, "app_users_repo.gen.go")
	wantSubs(t, a,
		"func GetAppUser(ctx context.Context, exec pgb.DBTX, id int64) (AppUser, error) {",
		"func ListAppUsers(ctx context.Context, exec pgb.DBTX, f AppUserFilter, opts ...pgb.ListOpt) ([]AppUser, error) {",
		"func scanAppUser(row pgx.CollectableRow) (AppUser, error) {",
		"appUsersFilterWhere(f)...",
	)
}

